def load_config() -> dict:
    return json.loads(CONFIG_PATH.read_text())


def http_get(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "OpenAIKit-generator"})
    token = os.environ.get("GITHUB_TOKEN")
    if token and url.startswith("https://api.github.com/"):
        request.add_header("Authorization", f"Bearer {token}")
    with urllib.request.urlopen(request, timeout=120) as response:
        return response.read()


def spec_cache_path(config: dict) -> Path:
    return CACHE / f"openapi-{config['spec']['commit']}.json"


def fetch_spec(config: dict) -> Path:
    path = spec_cache_path(config)
    spec = config["spec"]
    if path.exists() and hashlib.sha256(path.read_bytes()).hexdigest() == spec["sha256"]:
        return path
    url = f"https://raw.githubusercontent.com/{spec['repository']}/{spec['commit']}/{spec['path']}"
    print(f"Downloading {url}")
    data = http_get(url)
    digest = hashlib.sha256(data).hexdigest()
    if digest != spec["sha256"]:
        sys.exit(f"Spec checksum mismatch: expected {spec['sha256']}, got {digest}")
    CACHE.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return path


NAMING_RE = re.compile(
    r'<code title="(\w+) ([^"]+)">client\.([\w.]+)\.<a [^>]*>(\w+)</a>'
)


def refresh_naming(config: dict) -> None:
    naming = config["naming"]
    table: dict[str, list[str]] = {}
    for file in naming["files"]:
        url = f"https://raw.githubusercontent.com/{naming['repository']}/{naming['commit']}/{file}"
        text = http_get(url).decode("utf-8")
        for verb, path, chain, method in NAMING_RE.findall(text):
            table[f"{verb} {path}"] = [chain, method]
    NAMING_PATH.write_text(json.dumps(table, indent=1, sort_keys=True) + "\n")
    print(f"Wrote {len(table)} operation names to {NAMING_PATH.relative_to(ROOT)}")


def latest_commit(repository: str) -> str:
    data = json.loads(http_get(f"https://api.github.com/repos/{repository}/commits/HEAD"))
    return data["sha"]


def bump(config: dict) -> None:
    spec = config["spec"]
    spec["commit"] = latest_commit(spec["repository"])
    url = f"https://raw.githubusercontent.com/{spec['repository']}/{spec['commit']}/{spec['path']}"
    data = http_get(url)
    spec["sha256"] = hashlib.sha256(data).hexdigest()
    CACHE.mkdir(parents=True, exist_ok=True)
    spec_cache_path(config).write_bytes(data)
    config["naming"]["commit"] = latest_commit(config["naming"]["repository"])
    CONFIG_PATH.write_text(json.dumps(config, indent=2) + "\n")
    refresh_naming(config)
    print(f"Pinned spec {spec['commit']} and naming {config['naming']['commit']}")


