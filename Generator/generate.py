class Emitter:
    def __init__(self, builder: Builder):
        self.builder = builder
        self.by_id: dict[int, Decl] = {}
        self.all_tops: list[Decl] = list(builder.top.values()) + builder.extra_tops
        for top in self.all_tops:
            self.index(top)
        self.top_by_component = builder.top

    def index(self, decl: Decl):
        self.by_id[decl.id] = decl
        for child in decl.nested:
            self.index(child)

    def resolve(self, text: str) -> str:
        def replace(match):
            key = match.group(1)
            if key.startswith("top:"):
                return self.top_by_component[key[4:]].full_name()
            return self.by_id[int(key)].full_name()

        return re.sub("⟦([^⟧]+)⟧", replace, text)

    def referenced_tops(self, decl: Decl, acc: set):
        texts = []
        if isinstance(decl, Struct):
            texts = [p.type_text for p in decl.props]
        elif isinstance(decl, Union):
            texts = [c.type_text for c in decl.cases]
        elif isinstance(decl, Alias):
            texts = [decl.target or ""]
        for text in texts:
            for key in re.findall("⟦([^⟧]+)⟧", text):
                if key.startswith("top:"):
                    acc.add(self.top_by_component[key[4:]].name)
                else:
                    acc.add(self.by_id[int(key)].top().name)
            for word in re.findall(r"\b[A-Z][A-Za-z0-9_]*\b", re.sub("⟦[^⟧]+⟧", "", text)):
                acc.add(word)
        for child in decl.nested:
            self.referenced_tops(child, acc)

    def fix_shadowing(self):
        """Rename nested types whose names would shadow a top-level type used in the same tree."""
        for top in self.all_tops:
            referenced: set = set()
            self.referenced_tops(top, referenced)
            referenced.discard(top.name)
            stack = list(top.nested)
            while stack:
                decl = stack.pop()
                if decl.name in referenced:
                    siblings = decl.parent.local_names() if decl.parent else set()
                    base = decl.name + "Value"
                    name = base
                    n = 2
                    while name in siblings or name in referenced:
                        name = f"{base}{n}"
                        n += 1
                    decl.name = name
                stack.extend(decl.nested)

    # -- declaration rendering -------------------------------------------------

    def render(self, decl: Decl, indent: str = "") -> str:
        if isinstance(decl, Struct):
            return self.render_struct(decl, indent)
        if isinstance(decl, Union):
            return self.render_union(decl, indent)
        if isinstance(decl, OpenEnum):
            return self.render_enum(decl, indent)
        if isinstance(decl, Alias):
            return doc_comment(decl.doc, indent) + f"{indent}public typealias {decl.name} = {self.resolve(decl.target or 'JSONValue')}\n"
        raise TypeError(decl)

    def prop_type(self, prop: Prop) -> str:
        text = self.resolve(prop.type_text)
        if prop.optional and not text.endswith("?") and text != "JSONValue":
            text += "?"
        if prop.optional and text == "JSONValue":
            text = "JSONValue?"
        return text

    def render_struct(self, decl: Struct, indent: str) -> str:
        i1 = indent + "    "
        i2 = i1 + "    "
        out = doc_comment(decl.doc, indent)
        out += f"{indent}public struct {decl.name}: OpenAIModel {{\n"
        for prop in decl.props:
            extra = ["- Note: Deprecated by OpenAI."] if prop.deprecated else None
            out += doc_comment(prop.doc, i1, extra)
            type_text = self.prop_type(prop)
            if prop.const is not None:
                out += f"{i1}public var {ident(prop.swift_name)}: {type_text} = {swift_string(prop.const)}\n"
            else:
                out += f"{i1}public var {ident(prop.swift_name)}: {type_text}\n"
        priority = {"model": 0, "input": 1, "messages": 2, "prompt": 3, "file": 4, "instructions": 5}
        settable = [p for p in decl.props if p.const is None]
        settable.sort(key=lambda p: (p.optional, priority.get(p.json_name, 99)))
        if decl.props:
            out += "\n"
        params = []
        for prop in settable:
            type_text = self.prop_type(prop)
            default = " = nil" if type_text.endswith("?") else ""
            params.append(f"{ident(prop.swift_name)}: {type_text}{default}")
        if len(params) <= 2:
            out += f"{i1}public init({', '.join(params)}) {{\n"
        else:
            out += f"{i1}public init(\n" + ",\n".join(f"{i2}{p}" for p in params) + f"\n{i1}) {{\n"
        for prop in settable:
            out += f"{i2}self.{prop.swift_name.strip('`')} = {ident(prop.swift_name)}\n"
        out += f"{i1}}}\n"
        out += self.render_coding(decl, i1)
        for child in decl.nested:
            out += "\n" + self.render(child, i1)
        out += f"{indent}}}\n"
        return out

    def render_coding(self, decl: Struct, indent: str) -> str:
        """Explicit Codable with string keys: no `CodingKeys` enum per type, which saves megabytes."""
        i2 = indent + "    "
        out = f"\n{indent}public init(from decoder: any Decoder) throws {{\n"
        if decl.props:
            out += f"{i2}let container = try decoder.container(keyedBy: OpenAIDynamicCodingKey.self)\n"
        else:
            out += f"{i2}_ = try decoder.container(keyedBy: OpenAIDynamicCodingKey.self)\n"
        for prop in decl.props:
            name = prop.swift_name.strip("`")
            key = swift_string(prop.json_name)
            type_text = self.prop_type(prop)
            base = type_text[:-1] if type_text.endswith("?") else type_text
            if prop.const is not None and not type_text.endswith("?"):
                out += f"{i2}self.{name} = try container.decodeIfPresent(String.self, forKey: {key}) ?? {swift_string(prop.const)}\n"
            elif type_text.endswith("?"):
                out += f"{i2}self.{name} = try container.decodeIfPresent({base}.self, forKey: {key})\n"
            else:
                out += f"{i2}self.{name} = try container.decode({base}.self, forKey: {key})\n"
        out += f"{indent}}}\n\n"
        out += f"{indent}public func encode(to encoder: any Encoder) throws {{\n"
        if decl.props:
            out += f"{i2}var container = encoder.container(keyedBy: OpenAIDynamicCodingKey.self)\n"
        else:
            out += f"{i2}_ = encoder.container(keyedBy: OpenAIDynamicCodingKey.self)\n"
        for prop in decl.props:
            name = prop.swift_name.strip("`")
            key = swift_string(prop.json_name)
            method = "encodeIfPresent" if self.prop_type(prop).endswith("?") else "encode"
            out += f"{i2}try container.{method}(self.{name}, forKey: {key})\n"
        out += f"{indent}}}\n"
        return out

    def render_enum(self, decl: OpenEnum, indent: str) -> str:
        i1 = indent + "    "
        out = doc_comment(decl.doc, indent, ["This type is open: it accepts values the spec does not list yet."])
        out += f"{indent}public struct {decl.name}: OpenAIStringEnum {{\n"
        out += f"{i1}public let rawValue: String\n\n"
        out += f"{i1}public init(rawValue: String) {{\n{i1}    self.rawValue = rawValue\n{i1}}}\n"
        if decl.values:
            out += "\n"
        for name, value, doc in decl.values:
            out += doc_comment(doc, i1)
            out += f"{i1}public static let {ident(name)}: Self = {swift_string(value)}\n"
        if decl.values:
            out += f"\n{i1}public static var knownValues: [Self] {{\n{i1}    [{', '.join('.' + ident(n) for n, _, _ in decl.values)}]\n{i1}}}\n"
        else:
            out += f"\n{i1}public static var knownValues: [Self] {{ [] }}\n"
        for child in decl.nested:
            out += "\n" + self.render(child, i1)
        out += f"{indent}}}\n"
        return out

    def render_union(self, decl: Union, indent: str) -> str:
        i1 = indent + "    "
        i2 = i1 + "    "
        i3 = i2 + "    "
        protocols = "OpenAIModel"
        literal = decl.string_literal_case
        if literal is not None:
            protocols += ", ExpressibleByStringLiteral, ExpressibleByStringInterpolation"
        extra = None
        if decl.discriminator:
            extra = [f"Decoding picks the case from the `{decl.discriminator}` field. Values this version does not know decode as `.unknown`."]
        out = doc_comment(decl.doc, indent, extra)
        out += f"{indent}public indirect enum {decl.name}: {protocols} {{\n"
        for case in decl.cases:
            doc = case.doc
            if case.disc_values:
                doc = (doc + "\n\n" if doc else "") + f"`{decl.discriminator}`: " + ", ".join(f"`{v}`" for v in case.disc_values)
            out += doc_comment(doc, i1)
            out += f"{i1}case {ident(case.name)}({self.resolve(case.type_text)})\n"
        out += doc_comment("A value this version of OpenAIKit does not recognize, kept as raw JSON.", i1)
        out += f"{i1}case unknown(JSONValue)\n\n"
        if literal is not None:
            payload = self.resolve(literal.type_text).rstrip("?")
            token = re.fullmatch("\u27e6([^\u27e7]+)\u27e7", literal.type_text.rstrip("?"))
            target = None
            if token:
                key = token.group(1)
                target = self.top_by_component[key[4:]] if key.startswith("top:") else self.by_id[int(key)]
            value = f"{payload}(rawValue: value)" if isinstance(target, OpenEnum) else "value"
            out += f"{i1}public init(stringLiteral value: String) {{\n{i2}self = .{ident(literal.name)}({value})\n{i1}}}\n\n"
        # Decoding
        out += f"{i1}public init(from decoder: any Decoder) throws {{\n"
        out += f"{i2}let container = try decoder.singleValueContainer()\n"
        order = {"bool": 0, "int": 1, "double": 2, "string": 3}
        primitives = sorted([c for c in decl.cases if c.kind in order], key=lambda c: order[c.kind])
        for case in primitives:
            out += f"{i2}if let value = try? container.decode({self.resolve(case.type_text)}.self) {{\n{i3}self = .{ident(case.name)}(value)\n{i3}return\n{i2}}}\n"
        discriminated = [c for c in decl.cases if c.disc_values]
        if decl.discriminator and discriminated:
            out += f"{i2}if let keyed = try? decoder.container(keyedBy: OpenAIDynamicCodingKey.self),\n"
            out += f"{i2}   let discriminator = try? keyed.decode(String.self, forKey: OpenAIDynamicCodingKey({swift_string(decl.discriminator)})) {{\n"
            out += f"{i3}switch discriminator {{\n"
            for case in discriminated:
                labels = ", ".join(swift_string(v) for v in case.disc_values)
                out += f"{i3}case {labels}:\n{i3}    self = .{ident(case.name)}(try container.decode({self.resolve(case.type_text)}.self))\n{i3}    return\n"
            out += f"{i3}default:\n{i3}    break\n{i3}}}\n{i2}}}\n"
        fallbacks = [c for c in decl.cases if c.kind not in order and not c.disc_values and c.kind != "json"]
        fallbacks.sort(key=lambda c: 0 if c.kind == "array" else 1)
        for case in fallbacks:
            out += f"{i2}if let value = try? container.decode({self.resolve(case.type_text)}.self) {{\n{i3}self = .{ident(case.name)}(value)\n{i3}return\n{i2}}}\n"
        json_cases = [c for c in decl.cases if c.kind == "json"]
        if json_cases:
            out += f"{i2}self = .{ident(json_cases[0].name)}(try container.decode(JSONValue.self))\n"
        else:
            out += f"{i2}self = .unknown(try container.decode(JSONValue.self))\n"
        out += f"{i1}}}\n\n"
        # Encoding
        out += f"{i1}public func encode(to encoder: any Encoder) throws {{\n"
        out += f"{i2}var container = encoder.singleValueContainer()\n"
        out += f"{i2}switch self {{\n"
        for case in decl.cases:
            out += f"{i2}case .{ident(case.name)}(let value):\n{i3}try container.encode(value)\n"
        out += f"{i2}case .unknown(let value):\n{i3}try container.encode(value)\n"
        out += f"{i2}}}\n{i1}}}\n"
        for child in decl.nested:
            out += "\n" + self.render(child, i1)
        out += f"{indent}}}\n"
        return out


