def relax_required_from_examples(spec: Spec, builder: Builder):
    """The spec marks some properties required that its own examples omit; generate those as optional."""
    for name, schema in spec.schemas.items():
        meta = schema.get("x-oaiMeta") if isinstance(schema, dict) else None
        raw = meta.get("example") if isinstance(meta, dict) else None
        if raw is None:
            continue
        try:
            value = json.loads(raw) if isinstance(raw, str) else raw
        except ValueError:
            continue
        builder.relax_with_example(schema, value)
    for path, item in spec.doc["paths"].items():
        for method, op in item.items():
            if not isinstance(op, dict) or "operationId" not in op:
                continue
            success = [r for code, r in op["responses"].items() if code.startswith("2")]
            if not success:
                continue
            response = spec.deref(success[0]) if "$ref" in success[0] else success[0]
            content = response.get("content") or {}
            examples = (op.get("x-oaiMeta") or {}).get("examples")
            if isinstance(examples, dict):
                examples = [examples]
            for example in examples or []:
                raw = example.get("response") if isinstance(example, dict) else None
                if not isinstance(raw, str):
                    continue
                stripped = raw.strip()
                if stripped.startswith(("data:", "event:")) and "text/event-stream" in content:
                    schema = content["text/event-stream"].get("schema", {})
                    event_variants = builder.flat_variants((spec.deref(schema).get("oneOf") or spec.deref(schema).get("anyOf") or []))
                    wrapped = bool(event_variants) and all("event" in builder.object_shape(v)[0] and "data" in builder.object_shape(v)[0] for v in event_variants if builder.object_shape(v)[0])
                    parser_events = []
                    current = {}
                    for line in raw.splitlines() + [""]:
                        if not line.strip():
                            if "data" in current:
                                parser_events.append(current)
                            current = {}
                        elif line.startswith("event:"):
                            current["event"] = line[6:].strip()
                        elif line.startswith("data:"):
                            current["data"] = current.get("data", "") + line[5:].strip()
                    for event in parser_events:
                        try:
                            value = json.loads(event["data"])
                        except ValueError:
                            continue
                        if wrapped and "event" in event:
                            value = {"event": event["event"], "data": value}
                        builder.relax_with_example(schema, value)
                    continue
                json_schema = content.get("application/json", {}).get("schema")
                if not json_schema:
                    continue
                try:
                    value = json.loads(raw)
                except ValueError:
                    continue
                builder.relax_with_example(json_schema, value)


def build_spec_examples(spec: Spec, builder: Builder, ops: list, emitter: Emitter):
    """Collect the spec's own examples so the tests can decode each into its generated type."""
    examples = []
    for name, schema in sorted(spec.schemas.items()):
        meta = schema.get("x-oaiMeta") if isinstance(schema, dict) else None
        raw = meta.get("example") if isinstance(meta, dict) else None
        if raw is None:
            continue
        text = raw if isinstance(raw, str) else json.dumps(raw)
        try:
            json.loads(text)
        except ValueError:
            continue
        examples.append({"name": f"schema {name}", "type": builder.top[name].full_name(), "kind": "json", "body": text})
    for op in ops:
        for index, raw in enumerate(op.examples):
            label = f"{op.method} {op.path} #{index + 1}"
            stripped = raw.strip()
            if op.stream_event and (stripped.startswith("data:") or stripped.startswith("event:")):
                examples.append({"name": label + " (stream)", "type": emitter.resolve(op.stream_event), "kind": "sse", "wrapped": op.sse_wrapped, "body": raw})
                continue
            if op.result_kind != "json":
                continue
            try:
                json.loads(raw)
            except ValueError:
                continue
            examples.append({"name": label, "type": emitter.resolve(op.result), "kind": "json", "body": raw})
    types = sorted({e["type"] for e in examples})
    swift = HEADER + """
import Foundation
import OpenAIKit

/// Decoders for every type that has an example in the OpenAPI spec, keyed by type name.
enum SpecExampleDecoders {
    static let all: [String: @Sendable (Data) throws -> Bool] = [
"""
    for t in types:
        swift += f"        {swift_string(t)}: {{ try roundTrip({t}.self, $0) }},\n"
    swift += """    ]

    /// Decodes, re-encodes and decodes again; returns whether both decoded values are equal.
    static func roundTrip<T: Codable & Equatable>(_ type: T.Type, _ data: Data) throws -> Bool {
        let first = try JSONDecoder().decode(T.self, from: data)
        let second = try JSONDecoder().decode(T.self, from: JSONEncoder().encode(first))
        return first == second
    }
}
"""
    fixture = json.dumps(examples, indent=1, ensure_ascii=False) + "\n"
    return swift, fixture


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["fetch", "generate", "check", "naming", "bump"])
    args = parser.parse_args()
    config = load_config()
    if args.command == "fetch":
        print(fetch_spec(config))
    elif args.command == "naming":
        refresh_naming(config)
    elif args.command == "bump":
        bump(config)
        write_all(generate_files(load_config()))
    elif args.command == "generate":
        files = generate_files(config)
        write_all(files)
        print(f"Wrote {len(files)} files to {OUT.relative_to(ROOT)} and {TESTS.relative_to(ROOT)}")
    elif args.command == "check":
        files = generate_files(config)
        sources, tests, fixtures = split_outputs(files)
        expected = {f"Sources/{k}": v for k, v in sources.items()}
        expected.update({f"Tests/{k}": v for k, v in tests.items()})
        expected.update({f"Fixtures/{k}": v for k, v in fixtures.items()})
        actual = {f"Sources/{p.relative_to(OUT)}": p.read_text() for p in OUT.rglob("*.swift")} if OUT.exists() else {}
        generated_tests = TESTS / "Generated"
        if generated_tests.exists():
            actual.update({f"Tests/{p.relative_to(generated_tests)}": p.read_text() for p in generated_tests.rglob("*.swift")})
        for rel in fixtures:
            path = TESTS / "Fixtures" / rel
            if path.exists():
                actual[f"Fixtures/{rel}"] = path.read_text()
        if expected != actual:
            changed = sorted(set(expected) ^ set(actual) | {k for k in expected if actual.get(k) != expected[k]})
            print("Generated sources are out of date. Run `python3 Generator/generate.py generate`.")
            for name in changed[:50]:
                print(f"  {name}")
            sys.exit(1)
        print("Generated sources are up to date.")


if __name__ == "__main__":
    main()
