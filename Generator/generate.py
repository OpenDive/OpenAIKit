class Param:
    def __init__(self, json_name, swift_name, type_text, required, location, doc):
        self.json_name = json_name
        self.swift_name = swift_name
        self.type_text = type_text
        self.required = required
        self.location = location
        self.doc = doc


class Operation:
    def __init__(self):
        self.method = ""
        self.path = ""
        self.fixed_query: list[tuple[str, str]] = []
        self.chain: list[str] = []
        self.name = ""
        self.summary = None
        self.description = None
        self.deprecated = False
        self.path_params: list[Param] = []
        self.query_params: list[Param] = []
        self.header_params: list[Param] = []
        self.body_type: str | None = None
        self.body_required = False
        self.body_kind: str | None = None  # json | multipart | raw
        self.body_content_type: str | None = None
        self.result: str = "Void"  # swift type, "Data", "String" or "Void"
        self.result_kind = "void"  # json | data | text | void
        self.text_variant = False
        self.stream_event: str | None = None
        self.stream_kind = None  # body | query | only | override
        self.stream_override = None
        self.sse_wrapped = False
        self.admin = False
        self.beta_header: str | None = None
        self.paging = None  # (cursor param, item type, cursor expression kind)
        self.examples: list[str] = []
        self.operation_id = ""


class OperationBuilder:
    def __init__(self, spec: Spec, builder: Builder, naming: dict, config: dict):
        self.spec = spec
        self.builder = builder
        self.naming = naming
        self.config = config
        self.ops: list[Operation] = []
        self.param_holders: dict[str, Struct] = {}

    def holder(self, chain: list[str]) -> Struct:
        key = ".".join(chain)
        if key not in self.param_holders:
            name = "".join(pascal(c) for c in chain) + "Resource"
            decl = Struct(name, None, None)
            self.param_holders[key] = decl
        return self.param_holders[key]

    def fallback_name(self, method: str, path: str):
        segments = [s for s in path.split("?")[0].strip("/").split("/")]
        static = [s for s in segments if not s.startswith("{")]
        last_is_param = segments[-1].startswith("{")
        verbs = {"get": "retrieve" if last_is_param else "list", "post": "update" if last_is_param else "create", "delete": "delete"}
        return ".".join(static), verbs.get(method, method)

    def build(self):
        for path, item in self.spec.doc["paths"].items():
            for method, op in item.items():
                if not isinstance(op, dict) or "operationId" not in op:
                    continue
                self.ops.append(self.build_op(path, method, op, item))
        self.ops.sort(key=lambda o: (".".join(o.chain), o.name, o.path))

    def build_op(self, path: str, method: str, op: dict, item: dict) -> Operation:
        o = Operation()
        o.method = method.upper()
        o.operation_id = op["operationId"]
        base_path, _, query = path.partition("?")
        o.path = base_path
        if query:
            o.fixed_query = [tuple(pair.split("=", 1)) for pair in query.split("&")]
        chain, name = self.naming.get(f"{method} {path}") or self.fallback_name(method, path)
        o.chain = [camel(part) for part in chain.split(".")]
        o.name = camel(name)
        o.summary = op.get("summary")
        o.description = op.get("description")
        o.deprecated = bool(op.get("deprecated"))
        security = op.get("security") or []
        o.admin = any("AdminApiKeyAuth" in entry for entry in security)
        for prefix, header in self.config["betaHeaders"].items():
            if chain == prefix or chain.startswith(prefix + "."):
                o.beta_header = header
        holder = self.holder(o.chain)
        params = list(item.get("parameters", [])) + list(op.get("parameters", []))
        used = set()
        for raw in params:
            param = self.spec.deref(raw) if "$ref" in raw else raw
            location = param["in"]
            json_name = param["name"]
            if location == "header":
                lower = json_name.lower()
                swift = "betas" if lower == "openai-beta" else camel(json_name)
            else:
                swift = camel(json_name)
            while swift in used or swift in ("options", "request"):
                swift += "Value"
            used.add(swift)
            schema = param.get("schema", {})
            if location == "path":
                type_text = "String"
            else:
                type_text, _ = self.builder.type_of(schema, holder, o.name + pascal(json_name))
            p = Param(json_name, swift, type_text, bool(param.get("required")), location, param.get("description"))
            {"path": o.path_params, "query": o.query_params, "header": o.header_params}.get(location, []).append(p)
        # Keep path params in path order.
        order = re.findall(r"\{([^}]+)\}", base_path)
        o.path_params.sort(key=lambda p: order.index(p.json_name) if p.json_name in order else 99)

        body = op.get("requestBody")
        if body:
            body = self.spec.deref(body) if "$ref" in body else body
            content = body.get("content", {})
            o.body_required = bool(body.get("required"))
            chosen = None
            for ct in ("multipart/form-data", "application/json"):
                if ct in content:
                    chosen = ct
                    break
            if chosen is None and content:
                chosen = next(iter(content))
            schema = content[chosen].get("schema", {})
            if chosen == "multipart/form-data":
                o.body_kind = "multipart"
                o.body_type = self.multipart_type(schema, o)
            elif chosen == "application/json":
                o.body_kind = "json"
                if "$ref" in schema:
                    o.body_type, _ = self.builder.ref_type(schema["$ref"])
                else:
                    text, _ = self.builder.type_of(schema, None, pascal(o.operation_id) + "Request")
                    o.body_type = text
            else:
                o.body_kind = "raw"
                o.body_content_type = chosen
                o.body_type = "String"

        self.build_result(o, op)
        self.build_paging(o)
        examples = (op.get("x-oaiMeta") or {}).get("examples")
        if isinstance(examples, dict):
            examples = [examples]
        o.examples = [e["response"] for e in examples or [] if isinstance(e, dict) and isinstance(e.get("response"), str)]
        return o

    def multipart_type(self, schema, o: Operation) -> str:
        if "$ref" in schema:
            text, _ = self.builder.ref_type(schema["$ref"])
            return text
        text, _ = self.builder.type_of(schema, None, pascal(o.operation_id) + "Form", "multipart")
        return text

    def has_binary(self, schema, depth=0) -> bool:
        if depth > 6:
            return False
        schema = self.spec.deref(schema)
        if not isinstance(schema, dict):
            return False
        if schema.get("format") == "binary":
            return True
        for key in ("properties",):
            for value in (schema.get(key) or {}).values():
                if self.has_binary(value, depth + 1):
                    return True
        for key in ("items", "additionalProperties"):
            if isinstance(schema.get(key), dict) and self.has_binary(schema[key], depth + 1):
                return True
        for key in ("allOf", "anyOf", "oneOf"):
            for value in schema.get(key, []):
                if self.has_binary(value, depth + 1):
                    return True
        return False

    def build_result(self, o: Operation, op: dict):
        success = [(code, self.spec.deref(r) if "$ref" in r else r) for code, r in op["responses"].items() if code.startswith("2")]
        if not success:
            return
        code, response = success[0]
        content = response.get("content") or {}
        if "text/event-stream" in content:
            schema = content["text/event-stream"].get("schema", {})
            event_text, _ = self.builder.type_of(schema, None, pascal(o.operation_id) + "Event")
            o.stream_event = event_text
            o.sse_wrapped = self.is_wrapped_event(schema)
            override = self.config.get("streamOverrides", {}).get(f"{o.method.lower()} {o.path}")
            if override:
                o.stream_kind = "override"
                o.stream_override = override
            elif o.body_kind and self.body_has_stream(op):
                o.stream_kind = "body"
            elif any(p.json_name == "stream" for p in o.query_params):
                o.stream_kind = "query"
            elif len(content) == 1:
                o.stream_kind = "only"
            else:
                o.stream_kind = "body" if o.body_kind else None
        json_schema = content.get("application/json", {}).get("schema")
        if json_schema is not None and json_schema.get("type") != "string":
            o.result_schema = json_schema
            if "$ref" in json_schema:
                o.result, _ = self.builder.ref_type(json_schema["$ref"])
            else:
                o.result, _ = self.builder.type_of(json_schema, None, pascal(o.operation_id) + "Response")
            o.result_kind = "json"
            if "text/plain" in content:
                o.text_variant = True
            return
        others = [ct for ct in content if ct != "text/event-stream"]
        if not others:
            if o.stream_kind == "only":
                o.result_kind = "stream"
            return
        if any(ct in ("application/sdp", "text/plain") for ct in others):
            o.result, o.result_kind = "String", "text"
        else:
            o.result, o.result_kind = "Data", "data"

    def is_wrapped_event(self, schema) -> bool:
        schema = self.spec.deref(schema)
        variants = schema.get("oneOf") or schema.get("anyOf") or []
        if not variants:
            return False
        checked = 0
        for variant in variants:
            props, required = self.builder.object_shape(variant)
            if not props:
                continue
            checked += 1
            if not ("event" in props and "data" in props and len(props) <= 3):
                return False
        return checked > 0

    def body_has_stream(self, op) -> bool:
        body = op.get("requestBody")
        if not body:
            return False
        for content in body.get("content", {}).values():
            props, _ = self.builder.object_shape(content.get("schema", {}))
            if "stream" in props:
                return True
        return False

    def build_paging(self, o: Operation):
        if o.result_kind != "json" or o.method != "GET":
            return
        names = {p.json_name for p in o.query_params}
        schema = getattr(o, "result_schema", None)
        if schema is None:
            return
        schema = self.spec.deref(schema)
        props, _ = self.builder.object_shape(schema)
        if "data" not in props:
            return
        data = self.spec.deref(props["data"])
        data, _ = strip_null(data)
        if not isinstance(data, dict) or data.get("type") != "array":
            return
        _, data_required = self.builder.object_shape(schema)
        if "data" not in data_required:
            return
        item_text = "\u27e6PAGE\u27e7"
        if "after" in names and "has_more" in props:
            if "last_id" in props:
                o.paging = ("after", item_text, "lastID", "hasMore")
            else:
                item_schema = self.spec.deref(data.get("items", {}))
                item_props, _ = self.builder.object_shape(item_schema) if isinstance(item_schema, dict) else ({}, set())
                if "id" in item_props:
                    o.paging = ("after", item_text, "data.last?.id", "hasMore")
        elif "page" in names and "next_page" in props:
            o.paging = ("page", item_text, "nextPage", "hasMore" if "has_more" in props else None)


class ResourceEmitter:
    def __init__(self, emitter: Emitter, ops: list[Operation], holders: dict[str, Struct]):
        self.emitter = emitter
        self.ops = ops
        self.holders = holders
        self.page_types: set = set()

    def tree(self):
        nodes: dict[str, dict] = {}
        for op in self.ops:
            for depth in range(1, len(op.chain) + 1):
                key = ".".join(op.chain[:depth])
                nodes.setdefault(key, {"children": set(), "ops": []})
                if depth > 1:
                    nodes[".".join(op.chain[: depth - 1])]["children"].add(key)
            nodes[".".join(op.chain)]["ops"].append(op)
        return nodes

    def resource_name(self, key: str) -> str:
        return "".join(pascal(part) for part in key.split(".")) + "Resource"

    def render_all(self) -> dict[str, str]:
        nodes = self.tree()
        files: dict[str, str] = {}
        roots = sorted(k for k in nodes if "." not in k)
        root_out = HEADER + "\nimport Foundation\n\npublic extension OpenAI {\n"
        for key in roots:
            root_out += f"    /// Operations under `{key}`.\n    var {ident(key)}: {self.resource_name(key)} {{ {self.resource_name(key)}(client: self) }}\n\n"
        root_out = root_out.rstrip("\n") + "\n}\n"
        files["OpenAI+Resources.swift"] = root_out
        for root in roots:
            out = HEADER + "\nimport Foundation\n#if canImport(FoundationNetworking)\nimport FoundationNetworking\n#endif\n"
            stack = [root]
            while stack:
                key = stack.pop(0)
                out += "\n" + self.render_resource(key, nodes)
                stack.extend(sorted(nodes[key]["children"]))
            files[f"{self.resource_name(root)}.swift"] = out
        pages = HEADER + "\nimport Foundation\n\n// List responses that `...All` methods page through.\n"
        for name in sorted(self.page_types):
            pages += f"extension {name}: OpenAIPage {{}}\n"
        files["OpenAIPage+Conformances.swift"] = pages
        return files

    def render_resource(self, key: str, nodes) -> str:
        name = self.resource_name(key)
        node = nodes[key]
        holder = self.holders.get(key)
        out = f"/// Operations under `client.{key}`.\npublic struct {name}: Sendable {{\n"
        out += "    let client: OpenAI\n\n    init(client: OpenAI) {\n        self.client = client\n    }\n"
        for child in sorted(node["children"]):
            last = child.split(".")[-1]
            out += f"\n    /// Operations under `client.{child}`.\n    public var {ident(last)}: {self.resource_name(child)} {{ {self.resource_name(child)}(client: client) }}\n"
        for op in node["ops"]:
            out += "\n" + self.render_op(op)
        if holder is not None:
            for child in holder.nested:
                out += "\n" + self.emitter.render(child, "    ")
        out += "}\n"
        return out

    def param_list(self, op: Operation, include_body=True, skip=()) -> list[str]:
        params = []
        for p in op.path_params:
            params.append(f"{ident(p.swift_name)}: String")
        if include_body and op.body_type:
            body = self.emitter.resolve(op.body_type)
            if op.body_required:
                params.append(f"_ body: {body}")
            else:
                params.append(f"_ body: {body.rstrip('?')}? = nil")
        for p in op.query_params + op.header_params:
            if p.json_name in skip:
                continue
            t = self.emitter.resolve(p.type_text)
            if p.required:
                params.append(f"{ident(p.swift_name)}: {t}")
            else:
                params.append(f"{ident(p.swift_name)}: {t.rstrip('?')}? = nil")
        params.append("options: OpenAIRequestOptions? = nil")
        return params

    def signature(self, name: str, params: list[str], tail: str) -> str:
        if len(params) <= 2:
            return f"    public func {ident(name)}({', '.join(params)}){tail} {{\n"
        joined = ",\n".join(f"        {p}" for p in params)
        return f"    public func {ident(name)}(\n{joined}\n    ){tail} {{\n"

    def docs(self, op: Operation, extra: list[str] | None = None, skip=()) -> str:
        text = op.summary or ""
        if op.description and op.description.strip() != (op.summary or "").strip():
            text = (text + "\n\n" if text else "") + op.description.strip()
        lines = [f"`{op.method} {op.path}{('?' + '&'.join(k + '=' + v for k, v in op.fixed_query)) if op.fixed_query else ''}`"]
        params = []
        for p in op.path_params + op.query_params + op.header_params:
            if p.json_name in skip:
                continue
            if p.doc:
                first = " ".join(p.doc.strip().split())
            else:
                first = f"The `{p.json_name}` {p.location} parameter."
            params.append(f"  - {p.swift_name}: {first}")
        if op.body_type:
            params.append("  - body: The request body.")
        params.append("  - options: Per-request overrides for timeouts, retries and headers.")
        lines += ["", "- Parameters:"] + params
        if op.admin:
            lines += ["", "Requires an admin API key (`Configuration.adminAPIKey`)."]
        if extra:
            lines += [""] + extra
        out = doc_comment(text, "    ", lines)
        if op.deprecated:
            out += "    @available(*, deprecated, message: \"Deprecated by OpenAI.\")\n"
        return out

    def request_lines(self, op: Operation, stream_flag: bool, skip_after=None) -> str:
        path = op.path
        for p in op.path_params:
            path = path.replace("{" + p.json_name + "}", f"\\(OpenAIRequest.escape({ident(p.swift_name)}))")
        lines = [f"        var request = OpenAIRequest(method: \"{op.method}\", path: \"{path}\")"]
        for k, v in op.fixed_query:
            lines.append(f"        request.addQuery({swift_string(k)}, {swift_string(v)})")
        for p in op.query_params:
            value = ident(p.swift_name)
            if skip_after and p.json_name == skip_after:
                value = "cursor"
            if stream_flag and op.stream_kind == "query" and p.json_name == "stream":
                value = "true"
            lines.append(f"        try request.addQuery({swift_string(p.json_name)}, {value})")
        for p in op.header_params:
            if p.swift_name == "betas":
                lines.append(f"        if let betas = {ident(p.swift_name)}, !betas.isEmpty {{ request.headers[{swift_string(p.json_name)}] = betas.map {{ String(describing: $0) }}.joined(separator: \",\") }}")
            else:
                lines.append(f"        if let value = {ident(p.swift_name)} {{ request.headers[{swift_string(p.json_name)}] = value }}")
        if op.beta_header:
            lines.append(f"        request.headers[\"OpenAI-Beta\"] = {swift_string(op.beta_header)}")
        if op.admin:
            lines.append("        request.authentication = .admin")
        if op.body_type:
            overrides = ""
            if stream_flag and op.stream_kind == "body":
                overrides = ", overrides: [\"stream\": true]"
            elif stream_flag and op.stream_kind == "override":
                o = op.stream_override
                overrides = f", overrides: [{swift_string(o['field'])}: {swift_string(o['value'])}]"
            if op.body_kind == "json":
                if op.body_required:
                    lines.append(f"        try request.setJSONBody(body{overrides})")
                else:
                    lines.append(f"        if let body {{ try request.setJSONBody(body{overrides}) }}")
            elif op.body_kind == "multipart":
                if op.body_required:
                    lines.append(f"        try request.setMultipartBody(body{overrides})")
                else:
                    lines.append(f"        if let body {{ try request.setMultipartBody(body{overrides}) }}")
            else:
                lines.append(f"        request.setRawBody(Data(body.utf8), contentType: {swift_string(op.body_content_type)})")
        if len(lines) == 1:
            lines[0] = lines[0].replace("var request", "let request", 1)
        return "\n".join(lines) + "\n"

    def body_alias(self, op: Operation) -> str:
        return ""

    def render_op(self, op: Operation) -> str:
        out = ""
        result = self.emitter.resolve(op.result) if op.result_kind == "json" else op.result
        if op.result_kind == "stream":
            event = self.emitter.resolve(op.stream_event)
            out += self.docs(op, ["- Returns: The server-sent events as they arrive."])
            out += self.signature(op.name, self.param_list(op), f" -> AsyncThrowingStream<{event}, any Error>")
            out += self.stream_body(op, event, stream_flag=False)
            out += "    }\n"
            return out
        tail = " async throws" + (f" -> {result}" if op.result_kind != "void" else "")
        out += self.docs(op)
        out += self.signature(op.name, self.param_list(op), tail)
        out += self.body_alias(op)
        out += self.request_lines(op, False)
        if op.result_kind == "json":
            out += f"        return try await client.perform(request, options: options, as: {result}.self)\n"
        elif op.result_kind == "data":
            out += "        return try await client.performData(request, options: options)\n"
        elif op.result_kind == "text":
            out += "        return String(decoding: try await client.performData(request, options: options), as: UTF8.self)\n"
        else:
            out += "        _ = try await client.performData(request, options: options)\n"
        out += "    }\n"
        if op.text_variant:
            out += "\n" + self.docs(op, ["Use this variant when `responseFormat` asks for plain text, SRT or WebVTT output."])
            out += self.signature(op.name + "Text", self.param_list(op), " async throws -> String")
            out += self.body_alias(op)
            out += self.request_lines(op, False)
            out += "        return String(decoding: try await client.performData(request, options: options), as: UTF8.self)\n    }\n"
        if op.stream_event and op.stream_kind in ("body", "query", "override"):
            event = self.emitter.resolve(op.stream_event)
            params = self.param_list(op, skip=("stream",) if op.stream_kind == "query" else ())
            out += "\n" + self.docs(op, ["Streams the result as server-sent events. Iterate it with `for try await event in ...`."], skip=("stream",) if op.stream_kind == "query" else ())
            out += self.signature(op.name + "Stream", params, f" -> AsyncThrowingStream<{event}, any Error>")
            out += self.stream_body(op, event, stream_flag=True)
            out += "    }\n"
        if op.paging:
            cursor_param, item_text, cursor_expr, has_more = op.paging
            item = f"{result}.Item"
            self.page_types.add(result)
            params = self.param_list(op, skip=(cursor_param,))
            out += "\n" + self.docs(op, ["Fetches every page in turn and yields each item. Pages load as you iterate."], skip=(cursor_param,))
            sig_params = params
            out += self.signature(op.name + "All" if op.name != "list" else "listAll", sig_params, f" -> OpenAIAutoPagingSequence<{item}>")
            out += "        let client = self.client\n"
            out += "        return OpenAIAutoPagingSequence { cursor in\n"
            body_lines = self.request_lines(op, False, skip_after=cursor_param)
            body_lines = "\n".join("    " + line if line else line for line in body_lines.splitlines()) + "\n"
            out += body_lines
            out += f"            let page = try await client.perform(request, options: options, as: {result}.self)\n"
            more = f"(page.{has_more} as Bool?) ?? false" if has_more else "true"
            out += f"            let next: String? = {more} ? page.{cursor_expr} : nil\n"
            out += "            return (page.data, next)\n        }\n    }\n"
        return out

    def stream_body(self, op: Operation, event: str, stream_flag: bool) -> str:
        out = "        let client = self.client\n"
        out += "        return client.stream(" + ("wrapped: true, " if op.sse_wrapped else "") + "as: " + event + ".self) {\n"
        lines = self.request_lines(op, stream_flag)
        out += "\n".join("    " + line if line else line for line in lines.splitlines()) + "\n"
        out += "            return (request, options)\n        }\n"
        return out


