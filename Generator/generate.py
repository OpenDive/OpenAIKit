class Spec:
    def __init__(self, document: dict):
        self.doc = document
        self.schemas: dict = document["components"]["schemas"]
        self.responses: dict = document["components"].get("responses", {})

    def ref_name(self, ref: str) -> str:
        return ref.split("/")[-1]

    def deref(self, schema):
        seen = 0
        while isinstance(schema, dict) and "$ref" in schema:
            ref = schema["$ref"]
            if ref.startswith("#/components/schemas/"):
                schema = self.schemas[self.ref_name(ref)]
            elif ref.startswith("#/components/responses/"):
                schema = self.responses[self.ref_name(ref)]
            else:
                raise ValueError(f"Unsupported $ref {ref}")
            seen += 1
            if seen > 50:
                raise ValueError("Reference cycle")
        return schema


def is_null_schema(schema) -> bool:
    return isinstance(schema, dict) and (schema.get("type") == "null" or ("const" in schema and schema["const"] is None))


def type_list_split(schema: dict):
    """Expand `type: [a, b]` into a list of single-type schemas."""
    types = [t for t in schema["type"] if t != "null"]
    out = []
    for t in types:
        copy = {k: v for k, v in schema.items() if k not in ("type", "enum", "description", "default")}
        copy["type"] = t
        if t == "string" and "enum" in schema:
            copy["enum"] = [v for v in schema["enum"] if isinstance(v, str)]
        if t != "array":
            copy.pop("items", None)
        if t != "object":
            copy.pop("properties", None)
            copy.pop("required", None)
            copy.pop("additionalProperties", None)
        out.append(copy)
    return out, "null" in schema["type"]


def strip_null(schema):
    """Return (schema without the null option, nullable)."""
    if not isinstance(schema, dict):
        return schema, False
    nullable = bool(schema.get("nullable"))
    if isinstance(schema.get("type"), list):
        parts, has_null = type_list_split(schema)
        nullable = nullable or has_null
        if len(parts) == 1:
            merged = dict(parts[0])
            if "description" in schema:
                merged["description"] = schema["description"]
            return merged, nullable
        if not parts:
            return None, True
        return {"anyOf": parts, "description": schema.get("description")}, nullable
    for key in ("anyOf", "oneOf"):
        if key in schema:
            variants = schema[key]
            non_null = [v for v in variants if not is_null_schema(v)]
            if len(non_null) != len(variants):
                nullable = True
                if not non_null:
                    return None, True
                if len(non_null) == 1:
                    inner = non_null[0]
                    inner_desc = schema.get("description")
                    if inner_desc and isinstance(inner, dict) and "$ref" not in inner and "description" not in inner:
                        inner = dict(inner, description=inner_desc)
                    inner, inner_nullable = strip_null(inner)
                    return inner, True
                copy = dict(schema)
                copy[key] = non_null
                return copy, True
    return schema, nullable


def const_values(schema) -> list | None:
    if not isinstance(schema, dict):
        return None
    if "const" in schema and isinstance(schema["const"], str):
        return [schema["const"]]
    if "enum" in schema:
        values = [v for v in schema["enum"] if isinstance(v, str)]
        if values and len(values) == len([v for v in schema["enum"] if v is not None]) and len(values) <= 3 and schema.get("x-stainless-const", len(values) == 1):
            return values
    if schema.get("x-stainless-const") and isinstance(schema.get("default"), str):
        return [schema["default"]]
    return None


def single_const(schema) -> str | None:
    values = const_values(schema)
    if values and len(values) == 1:
        return values[0]
    return None


