class Decl:
    counter = 0

    def __init__(self, name: str, parent: "Decl | None", doc: str | None):
        Decl.counter += 1
        self.id = Decl.counter
        self.name = name
        self.parent = parent
        self.doc = doc
        self.nested: list[Decl] = []
        self.deprecated = False
        if parent is not None:
            parent.nested.append(self)

    @property
    def token(self) -> str:
        return f"⟦{self.id}⟧"

    def top(self) -> "Decl":
        node = self
        while node.parent is not None:
            node = node.parent
        return node

    def full_name(self) -> str:
        if self.parent is None:
            return self.name
        return self.parent.full_name() + "." + self.name

    def local_names(self) -> set:
        return {child.name for child in self.nested}


class Prop:
    def __init__(self, json_name, swift_name, type_text, optional, const, doc, deprecated):
        self.json_name = json_name
        self.swift_name = swift_name
        self.type_text = type_text
        self.optional = optional
        self.const = const
        self.doc = doc
        self.deprecated = deprecated


class Struct(Decl):
    def __init__(self, name, parent, doc):
        super().__init__(name, parent, doc)
        self.props: list[Prop] = []


class Case:
    def __init__(self, name, type_text, kind, disc_values=None, doc=None):
        self.name = name
        self.type_text = type_text
        self.kind = kind  # string | int | double | bool | array | object | json
        self.disc_values = disc_values or []
        self.doc = doc


class Union(Decl):
    def __init__(self, name, parent, doc):
        super().__init__(name, parent, doc)
        self.cases: list[Case] = []
        self.discriminator: str | None = None
        self.string_literal_case: Case | None = None


class OpenEnum(Decl):
    def __init__(self, name, parent, doc):
        super().__init__(name, parent, doc)
        self.values: list[tuple[str, str, str | None]] = []


class Alias(Decl):
    def __init__(self, name, parent, doc, target):
        super().__init__(name, parent, doc)
        self.target = target


