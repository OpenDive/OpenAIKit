def group_key(name: str) -> str:
    words = re.findall(r"[A-Z][a-z0-9]*|[a-z0-9]+|_", name)
    first = words[0] if words else name
    return first or "Misc"


def split_outputs(files: dict[str, str]):
    sources = {k: v for k, v in files.items() if not k.startswith("__")}
    tests = {k[len("__tests__/"):]: v for k, v in files.items() if k.startswith("__tests__/")}
    fixtures = {k[len("__fixtures__/"):]: v for k, v in files.items() if k.startswith("__fixtures__/")}
    return sources, tests, fixtures


def write_all(files: dict[str, str]):
    sources, tests, fixtures = split_outputs(files)
    write_outputs(OUT, sources)
    write_outputs(TESTS / "Generated", tests)
    for rel, content in fixtures.items():
        path = TESTS / "Fixtures" / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


def write_outputs(target: Path, files: dict[str, str]):
    if target.exists():
        shutil.rmtree(target)
    for rel, content in files.items():
        path = target / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


def generate_files(config: dict) -> dict[str, str]:
    spec = Spec(json.loads(fetch_spec(config).read_text()))
    naming = json.loads(NAMING_PATH.read_text()) if NAMING_PATH.exists() else {}
    builder = Builder(spec)
    relax_required_from_examples(spec, builder)
    builder.build_components()
    build_webhook_union(spec, builder)
    ops_builder = OperationBuilder(spec, builder, naming, config)
    ops_builder.build()
    emitter = Emitter(builder)
    for holder in ops_builder.param_holders.values():
        emitter.index(holder)
    emitter.all_tops.extend(ops_builder.param_holders.values())
    emitter.fix_shadowing()

    files: dict[str, str] = {}
    groups: dict[str, list[Decl]] = {}
    for decl in sorted(list(builder.top.values()) + builder.extra_tops, key=lambda d: d.name):
        groups.setdefault(group_key(decl.name), []).append(decl)
    for key, decls in sorted(groups.items()):
        chunk: list[str] = []
        size = 0
        part = 1
        for decl in decls:
            text = emitter.render(decl)
            chunk.append(text)
            size += text.count("\n")
            if size > 4000:
                files[f"Models/{key}{'' if part == 1 else part}.swift"] = HEADER + "\nimport Foundation\n\n" + "\n".join(chunk)
                chunk, size, part = [], 0, part + 1
        if chunk:
            files[f"Models/{key}{'' if part == 1 else part}.swift"] = HEADER + "\nimport Foundation\n\n" + "\n".join(chunk)

    resources = ResourceEmitter(emitter, ops_builder.ops, ops_builder.param_holders)
    for name, content in resources.render_all().items():
        files[f"Resources/{name}"] = content

    test_swift, test_fixture = build_spec_examples(spec, builder, ops_builder.ops, emitter)
    files["__tests__/SpecExampleDecoders.swift"] = test_swift
    files["__fixtures__/spec-examples.json"] = test_fixture

    meta = {
        "spec": config["spec"]["commit"],
        "specVersion": spec.doc["info"]["version"],
        "operations": len(ops_builder.ops),
        "schemas": len(spec.schemas),
    }
    files["GeneratedMetadata.swift"] = HEADER + f"""
import Foundation

/// Facts about the OpenAPI document these sources were generated from.
public enum OpenAIGeneratedMetadata {{
    /// Commit of github.com/openai/openai-openapi the sources were generated from.
    public static let specCommit = {swift_string(meta['spec'])}
    /// The spec's `info.version`.
    public static let specVersion = {swift_string(meta['specVersion'])}
    /// Number of HTTP operations with a generated method.
    public static let operationCount = {meta['operations']}
    /// Number of schemas with a generated type.
    public static let schemaCount = {meta['schemas']}
}}
"""
    return files


