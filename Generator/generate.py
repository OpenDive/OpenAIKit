def split_words(name: str) -> list[str]:
    return [part for part in re.split(r"[^A-Za-z0-9]+", name) if part]


def join_words(parts: list[str]) -> str:
    out = ""
    for part in parts:
        if out and out[-1].isdigit() and part[0].isdigit():
            out += "_"
        out += part
    return out


def camel(name: str) -> str:
    parts = split_words(name)
    if not parts:
        return "value"
    first = parts[0]
    if first.isupper() and len(first) > 1:
        first = first.lower()
    else:
        first = first[0].lower() + first[1:]
    rest = []
    for part in parts[1:]:
        lower = part.lower()
        if lower in ACRONYMS:
            rest.append(ACRONYMS[lower])
        else:
            rest.append(part[0].upper() + part[1:])
    result = join_words([first] + rest)
    if result[0].isdigit():
        result = "_" + result
    return result


def pascal(name: str) -> str:
    parts = split_words(name)
    if not parts:
        return "Value"
    out = []
    for part in parts:
        lower = part.lower()
        if lower in ACRONYMS and part == lower:
            out.append(ACRONYMS[lower])
        else:
            out.append(part[0].upper() + part[1:])
    result = join_words(out)
    if result[0].isdigit():
        result = "_" + result
    return result


def ident(name: str) -> str:
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def enum_case_name(value: str) -> str:
    parts = split_words(str(value))
    if not parts:
        return "empty"
    first = parts[0]
    first = first.lower() if first.isupper() else first[0].lower() + first[1:]
    result = join_words([first] + [p[0].upper() + p[1:] for p in parts[1:]])
    if result[0].isdigit():
        result = "_" + result
    if result == "none":
        return "noneValue"
    if result in RESERVED_MEMBER_NAMES:
        return result + "Value"
    return result


def singular(word: str) -> str:
    if word.endswith("ies") and len(word) > 4:
        return word[:-3] + "y"
    if word.endswith("sses"):
        return word[:-2]
    if word.endswith("s") and not word.endswith("ss") and len(word) > 3:
        return word[:-1]
    return word + "Item"


def swift_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False).replace("\\/", "/")


def doc_comment(text: str | None, indent: str, extra: list[str] | None = None) -> str:
    lines: list[str] = []
    if text:
        for line in str(text).strip().splitlines():
            lines.append(line.rstrip())
    if extra:
        if lines:
            lines.append("")
        lines.extend(extra)
    if not lines:
        return ""
    return "".join(f"{indent}///{(' ' + line) if line else ''}\n" for line in lines)


