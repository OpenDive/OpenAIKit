class Builder:
    def __init__(self, spec: Spec):
        self.spec = spec
        self.top: dict[str, Decl] = {}
        self.top_names: dict[str, str] = {}
        self.info_cache: dict[str, dict] = {}
        self.extra_tops: list[Decl] = []
        self.relaxed: set = set()
        self.assign_top_names()

    # -- top-level names ---------------------------------------------------

    def assign_top_names(self):
        used = set()
        for name in self.spec.schemas:
            swift = name if re.fullmatch(r"[A-Z][A-Za-z0-9]*", name) else pascal(name)
            if swift in RESERVED_TYPE_NAMES:
                swift = swift + "Object"
            base = swift
            n = 2
            while swift in used:
                swift = f"{base}{n}"
                n += 1
            used.add(swift)
            self.top_names[name] = swift
        self.used_top = used

    def reserve_top_name(self, wanted: str) -> str:
        name = wanted
        if name in RESERVED_TYPE_NAMES:
            name = name + "Object"
        base = name
        n = 2
        while name in self.used_top:
            name = f"{base}{n}"
            n += 1
        self.used_top.add(name)
        return name

    # -- shallow information about components ---------------------------

    def info(self, name: str) -> dict:
        """Nullability and string-enum information for a component, without emitting."""
        if name in self.info_cache:
            return self.info_cache[name]
        self.info_cache[name] = {"nullable": False, "string_values": None, "stringlike": False}
        schema = self.spec.schemas[name]
        stripped, nullable = strip_null(schema)
        result = {"nullable": nullable, "string_values": None, "stringlike": False}
        if stripped is not None:
            stringlike, values = self.string_shape(stripped)
            result["stringlike"] = stringlike
            result["string_values"] = values
        self.info_cache[name] = result
        return result

    def string_shape(self, schema):
        """(is the schema only ever a string, known enum values or None)."""
        if not isinstance(schema, dict):
            return False, None
        if "$ref" in schema:
            info = self.info(self.spec.ref_name(schema["$ref"]))
            return info["stringlike"], info["string_values"]
        schema, _ = strip_null(schema)
        if schema is None:
            return False, None
        variants = schema.get("anyOf") or schema.get("oneOf")
        if variants:
            values: list[str] = []
            for variant in variants:
                ok, vals = self.string_shape(variant)
                if not ok:
                    return False, None
                if vals:
                    values.extend(v for v in vals if v not in values)
            return True, values or None
        if schema.get("type") == "string" or ("enum" in schema and all(isinstance(v, str) for v in schema["enum"] if v is not None) and schema.get("type") in (None, "string")) or isinstance(schema.get("const"), str):
            if schema.get("format") == "binary":
                return False, None
            if "enum" in schema:
                return True, [v for v in schema["enum"] if isinstance(v, str)]
            if "const" in schema:
                return True, [schema["const"]]
            return True, None
        return False, None

    def ref_type(self, ref: str):
        name = self.spec.ref_name(ref)
        if ref.startswith("#/components/responses/"):
            response = self.spec.responses[name]
            content = response.get("content", {}).get("application/json", {}).get("schema")
            return self.type_of(content, None, "Response") if content else ("JSONValue", False)
        decl = self.top.get(name)
        token = decl.token if decl else f"⟦top:{name}⟧"
        return token, self.info(name)["nullable"]

    # -- examples relax "required" ---------------------------------------------

    def relax_with_example(self, schema, value, depth=0):
        """Record required properties that one of the spec's own examples leaves out."""
        if depth > 40 or not isinstance(schema, dict):
            return
        schema = self.spec.deref(schema)
        stripped, _ = strip_null(schema)
        if not isinstance(stripped, dict):
            return
        schema = stripped
        if isinstance(value, list):
            if schema.get("type") == "array" and isinstance(schema.get("items"), dict):
                for item in value:
                    self.relax_with_example(schema["items"], item, depth + 1)
            for variant in schema.get("oneOf") or schema.get("anyOf") or []:
                resolved = self.spec.deref(variant)
                if isinstance(resolved, dict) and resolved.get("type") == "array":
                    self.relax_with_example(resolved, value, depth + 1)
            return
        if not isinstance(value, dict):
            return
        variants = schema.get("oneOf") or schema.get("anyOf")
        if variants:
            # Relax only the closest variant, and only when no variant fits the example as is.
            scored = []
            for variant in self.flat_variants(variants):
                if self.example_matches(variant, value):
                    scored.append((self.missing_required(variant, value), id(variant), variant))
            if not scored:
                return
            scored.sort(key=lambda entry: entry[0])
            best = [entry for entry in scored if entry[0] == scored[0][0]]
            if scored[0][0] == 0 or len(best) == 1:
                self.relax_with_example(best[0][2], value, depth + 1)
            return
        if not self.is_objectish(schema):
            return
        props, required = self.object_shape(schema)
        for key in required:
            if key not in value:
                self.relaxed.add((id(schema), key))
        for key, item in value.items():
            if key in props:
                self.relax_with_example(props[key], item, depth + 1)

    def flat_variants(self, variants):
        out = []
        for variant in variants:
            resolved = self.spec.deref(variant)
            stripped, _ = strip_null(resolved)
            if isinstance(stripped, dict) and (stripped.get("oneOf") or stripped.get("anyOf")) and not self.is_objectish(stripped):
                out.extend(self.flat_variants(stripped.get("oneOf") or stripped.get("anyOf")))
            elif not is_null_schema(variant):
                out.append(variant)
        return out

    def missing_required(self, variant, value) -> int:
        resolved = self.spec.deref(variant)
        stripped, _ = strip_null(resolved)
        if not isinstance(stripped, dict) or not self.is_objectish(stripped):
            return 0
        _, required = self.object_shape(stripped)
        return sum(1 for key in required if key not in value)

    def example_matches(self, variant, value) -> bool:
        resolved = self.spec.deref(variant)
        stripped, _ = strip_null(resolved)
        if not isinstance(stripped, dict):
            return False
        if stripped.get("oneOf") or stripped.get("anyOf"):
            return any(self.example_matches(v, value) for v in (stripped.get("oneOf") or stripped.get("anyOf")))
        if not self.is_objectish(stripped):
            return False
        props, _ = self.object_shape(stripped)
        for key, prop in props.items():
            constant = single_const(self.spec.deref(prop)) if isinstance(prop, dict) else None
            if constant is not None and key in value and value[key] != constant:
                return False
        return True

    # -- object property merge ---------------------------------------------

    def object_shape(self, schema, depth=0):
        """Merged (properties, required, description) for an object or allOf schema."""
        schema = self.spec.deref(schema)
        props: "OrderedDict[str, dict]" = OrderedDict()
        required: set = set()
        if not isinstance(schema, dict) or depth > 20:
            return props, required
        for part in schema.get("allOf", []):
            p, r = self.object_shape(part, depth + 1)
            for key, value in p.items():
                props[key] = value
            required |= r
        for key, value in (schema.get("properties") or {}).items():
            props[key] = value
        required |= set(schema.get("required") or [])
        return props, required

    def is_objectish(self, schema) -> bool:
        schema = self.spec.deref(schema)
        if not isinstance(schema, dict):
            return False
        if "properties" in schema or "allOf" in schema:
            return True
        return schema.get("type") == "object"

    # -- unique nested names -------------------------------------------------

    def nested_name(self, parent: Decl | None, wanted: str) -> str:
        wanted = pascal(wanted) if wanted else "Value"
        if wanted == "Type":
            wanted = "Kind"
        if parent is None:
            return self.reserve_top_name(wanted)
        taken = parent.local_names()
        ancestors = set()
        node = parent
        while node is not None:
            ancestors.add(node.name)
            node = node.parent
        candidates = [wanted, wanted + "Value"] + [f"{wanted}Value{n}" for n in range(2, 100)]
        for name in candidates:
            if name not in taken and name not in ancestors and name not in RESERVED_TYPE_NAMES:
                return name
        raise RuntimeError(f"No free name for {wanted}")

    # -- the main mapping ------------------------------------------------------

    def type_of(self, schema, parent: Decl | None, hint: str, mode: str = "json"):
        """Return (swift type text, optional) for a schema, emitting nested declarations under parent."""
        if schema is None or schema is True or schema == {}:
            return "JSONValue", False
        if not isinstance(schema, dict):
            return "JSONValue", False
        if "$ref" in schema:
            return self.ref_type(schema["$ref"])
        stripped, nullable = strip_null(schema)
        if stripped is None:
            return "JSONValue", True
        if stripped is not schema:
            text, optional = self.type_of(stripped, parent, hint, mode)
            return text, optional or nullable
        if "oneOf" in schema or "anyOf" in schema:
            return self.union_type(schema, parent, hint, mode)
        if "allOf" in schema:
            parts = schema["allOf"]
            if len(parts) == 1 and not schema.get("properties"):
                return self.type_of(parts[0], parent, hint, mode)
            if any(not self.is_objectish(p) for p in parts):
                objectish = [p for p in parts if self.is_objectish(p)]
                others = [p for p in parts if not self.is_objectish(p)]
                if len(others) == 1 and all(not self.object_shape(p)[0] for p in objectish):
                    return self.type_of(others[0], parent, hint, mode)
                return "JSONValue", False
            return self.struct_type(schema, parent, hint, mode), False
        t = schema.get("type")
        if "const" in schema and t is None:
            value = schema["const"]
            t = {str: "string", bool: "boolean", int: "integer", float: "number"}.get(type(value), None)
        if "enum" in schema:
            values = [v for v in schema["enum"] if v is not None]
            if values and all(isinstance(v, str) for v in values):
                if len(values) == 1 and t != "array":
                    return "String", False
                return self.open_enum(values, schema, parent, hint), False
            if values and all(isinstance(v, bool) for v in values):
                return "Bool", False
            if values and all(isinstance(v, int) for v in values):
                return "Int", False
            if values and all(isinstance(v, (int, float)) for v in values):
                return "Double", False
        if t == "string":
            if schema.get("format") == "binary":
                return "FileUpload", False
            return "String", False
        if t == "integer":
            return ("Int64" if schema.get("format") == "int64" else "Int"), False
        if t == "number":
            return "Double", False
        if t == "boolean":
            return "Bool", False
        if t == "array":
            items = schema.get("items")
            item_text, item_optional = self.type_of(items, parent, singular(hint), mode)
            if item_optional:
                item_text += "?"
            return f"[{item_text}]", False
        if t == "object" or "properties" in schema:
            if schema.get("properties"):
                return self.struct_type(schema, parent, hint, mode), False
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                value_text, value_optional = self.type_of(extra, parent, singular(hint) if hint else "Value", mode)
                if value_optional:
                    value_text += "?"
                return f"[String: {value_text}]", False
            return "JSONObject", False
        return "JSONValue", False

    def open_enum(self, values, schema, parent, hint) -> str:
        decl = OpenEnum(self.nested_name(parent, hint), parent, schema.get("description"))
        if parent is None:
            self.extra_tops.append(decl)
        self.fill_open_enum(decl, values, schema)
        return decl.token

    def fill_open_enum(self, decl: OpenEnum, values, schema):
        descriptions = schema.get("x-enumDescriptions") or {}
        used = set()
        for value in values:
            name = enum_case_name(value)
            base = name
            n = 2
            while name in used:
                name = f"{base}{n}"
                n += 1
            used.add(name)
            doc = descriptions.get(value) if isinstance(descriptions, dict) else None
            decl.values.append((name, value, doc))

    def struct_type(self, schema, parent, hint, mode) -> str:
        decl = Struct(self.nested_name(parent, hint), parent, schema.get("description"))
        if parent is None:
            self.extra_tops.append(decl)
        self.fill_struct(decl, schema, mode)
        return decl.token

    def fill_struct(self, decl: Struct, schema, mode):
        props, required = self.object_shape(schema)
        used = set()
        for json_name, prop_schema in props.items():
            if self.sdk_computed(prop_schema):
                # Properties such as `Response.output_text` are computed by SDKs, not sent by the API.
                continue
            swift = camel(json_name)
            base = swift
            n = 2
            while swift in used:
                swift = f"{base}{n}"
                n += 1
            used.add(swift)
            resolved = self.spec.deref(prop_schema) if isinstance(prop_schema, dict) else prop_schema
            description = None
            if isinstance(prop_schema, dict):
                description = prop_schema.get("description") or (resolved.get("description") if isinstance(resolved, dict) and "$ref" not in prop_schema else None)
            const = single_const(prop_schema) if isinstance(prop_schema, dict) and "$ref" not in prop_schema else None
            if const is not None:
                type_text, optional = "String", False
                _, optional = strip_null(prop_schema)
            else:
                type_text, optional = self.type_of(prop_schema, decl, json_name, mode)
            is_required = json_name in required and (id(self.spec.deref(schema)), json_name) not in self.relaxed
            if json_name in ALWAYS_OPTIONAL:
                is_required = False
            deprecated = isinstance(prop_schema, dict) and bool(prop_schema.get("deprecated"))
            decl.props.append(Prop(json_name, swift, type_text, optional or not is_required, const, description, deprecated))

    @staticmethod
    def sdk_computed(schema) -> bool:
        if not isinstance(schema, dict):
            return False
        if "x-oaiSupportedSDKs" in schema:
            return True
        return any(isinstance(v, dict) and "x-oaiSupportedSDKs" in v for v in (schema.get("anyOf") or schema.get("oneOf") or []))

    # -- unions -----------------------------------------------------------------

    def union_type(self, schema, parent, hint, mode):
        variants = schema.get("oneOf") or schema.get("anyOf") or []
        non_null = [v for v in variants if not is_null_schema(v)]
        nullable = len(non_null) != len(variants)
        flat = []
        for variant in non_null:
            if isinstance(variant, dict) and ("oneOf" in variant or "anyOf" in variant) and "$ref" not in variant and not variant.get("properties") and "discriminator" not in variant:
                inner, inner_null = strip_null(variant)
                nullable = nullable or inner_null
                if inner is None:
                    continue
                inner_variants = inner.get("oneOf") or inner.get("anyOf")
                if inner_variants:
                    flat.extend(inner_variants)
                    continue
                flat.append(inner)
            else:
                flat.append(variant)
        non_null = flat
        if not non_null:
            return "JSONValue", True
        if len(non_null) == 1:
            text, optional = self.type_of(non_null[0], parent, hint, mode)
            return text, optional or nullable

        # Only strings: one open enum.
        shapes = [self.string_shape(v) for v in non_null]
        if all(ok for ok, _ in shapes):
            enum_refs = [v for v, (ok, vals) in zip(non_null, shapes) if vals and isinstance(v, dict) and "$ref" in v]
            plain = [v for v, (ok, vals) in zip(non_null, shapes) if not vals]
            if len(enum_refs) == 1 and len(enum_refs) + len(plain) == len(non_null):
                text, optional = self.ref_type(enum_refs[0]["$ref"])
                return text, optional or nullable
            values: list[str] = []
            for _, vals in shapes:
                for value in vals or []:
                    if value not in values:
                        values.append(value)
            if not values:
                return "String", nullable
            return self.open_enum(values, schema, parent, hint), nullable

        resolved = [self.spec.deref(v) if isinstance(v, dict) else v for v in non_null]
        kinds = [self.variant_kind(v) for v in non_null]
        if all(k == "int" for k in kinds):
            return "Int", nullable
        if all(k in ("int", "double") for k in kinds):
            return "Double", nullable

        decl = Union(self.nested_name(parent, hint), parent, schema.get("description"))
        if parent is None:
            self.extra_tops.append(decl)
        self.fill_union(decl, schema, non_null, resolved, kinds, mode)
        return decl.token, nullable

    def variant_kind(self, variant) -> str:
        schema = self.spec.deref(variant)
        if not isinstance(schema, dict) or schema == {}:
            return "json"
        stripped, _ = strip_null(schema)
        if stripped is None:
            return "json"
        schema = stripped
        if "oneOf" in schema or "anyOf" in schema:
            ok, _ = self.string_shape(schema)
            if ok:
                return "string"
            inner = [self.variant_kind(v) for v in (schema.get("oneOf") or schema.get("anyOf")) if not is_null_schema(v)]
            if inner and all(k == "object" for k in inner):
                return "object"
            if inner and all(k in ("int", "double") for k in inner):
                return "double" if "double" in inner else "int"
            return "union"
        if schema.get("format") == "binary":
            return "file"
        ok, _ = self.string_shape(schema)
        if ok:
            return "string"
        t = schema.get("type")
        if "const" in schema and t is None:
            t = {str: "string", bool: "boolean", int: "integer", float: "number"}.get(type(schema["const"]))
        if t == "integer":
            return "int"
        if t == "number":
            return "double"
        if t == "boolean":
            return "bool"
        if t == "array":
            return "array"
        if t == "string":
            return "string"
        if t == "object" or "properties" in schema or "allOf" in schema:
            return "object"
        return "json"

    def discriminator_values(self, variant, prop) -> list | None:
        props, _ = self.object_shape(variant)
        if prop not in props:
            return None
        return const_values(self.spec.deref(props[prop]) if "$ref" in props[prop] else props[prop])

    def fill_union(self, decl: Union, schema, variants, resolved, kinds, mode):
        # Several string-shaped variants (an enum plus "any string", say) become one case,
        # so the union stays ExpressibleByStringLiteral and every string decodes the same way.
        string_indices = [i for i, k in enumerate(kinds) if k == "string"]
        if len(string_indices) > 1:
            merged = {"anyOf": [variants[i] for i in string_indices]}
            first = string_indices[0]
            keep = [i for i in range(len(variants)) if i not in string_indices[1:]]
            variants = [merged if i == first else variants[i] for i in keep]
            resolved = [merged if i == first else resolved[i] for i in keep]
            kinds = [kinds[i] for i in keep]
        object_variants = [v for v, k in zip(variants, kinds) if k == "object"]
        discriminator = (schema.get("discriminator") or {}).get("propertyName")
        mapping = (schema.get("discriminator") or {}).get("mapping") or {}
        if not discriminator and len(object_variants) >= 2:
            for candidate in ("type", "object", "role", "event", "action", "status"):
                values = [self.discriminator_values(v, candidate) for v in object_variants]
                if all(values) and len({x for vals in values for x in vals}) == sum(len(v) for v in values):
                    discriminator = candidate
                    break
        if discriminator and not object_variants:
            discriminator = None
        decl.discriminator = discriminator
        reverse_mapping: dict[str, list[str]] = {}
        for value, ref in mapping.items():
            reverse_mapping.setdefault(ref, []).append(value)

        names_from_refs = self.ref_case_names([v for v in variants if isinstance(v, dict) and "$ref" in v])
        used = set()
        array_variants = sum(1 for k in kinds if k == "array")

        def unique(name):
            name = enum_case_name(name)
            if name in RESERVED_MEMBER_NAMES or name == "none":
                name = name + "Value"
            base = name
            n = 2
            while name in used:
                name = f"{base}{n}"
                n += 1
            used.add(name)
            return name

        seen_values: set = set()
        for index, (variant, kind) in enumerate(zip(variants, kinds)):
            title = variant.get("title") if isinstance(variant, dict) else None
            disc_values = []
            if discriminator and kind == "object":
                if isinstance(variant, dict) and "$ref" in variant and variant["$ref"] in reverse_mapping:
                    disc_values = reverse_mapping[variant["$ref"]]
                else:
                    disc_values = self.discriminator_values(variant, discriminator) or []
                disc_values = [v for v in disc_values if v not in seen_values]
                seen_values.update(disc_values)
            if isinstance(variant, dict) and "$ref" in variant:
                case_hint = names_from_refs.get(variant["$ref"]) or self.spec.ref_name(variant["$ref"])
            elif disc_values:
                case_hint = disc_values[0]
            elif title:
                case_hint = title
            elif kind == "string":
                case_hint = "string"
            elif kind == "int":
                case_hint = "integer"
            elif kind == "double":
                case_hint = "number"
            elif kind == "bool":
                case_hint = "bool"
            elif kind == "array":
                case_hint = "array"
            elif kind == "json":
                case_hint = "json"
            elif kind == "file":
                case_hint = "file"
            else:
                case_hint = f"variant{index + 1}"
            if disc_values and isinstance(variant, dict) and "$ref" in variant and len(disc_values) == 1:
                case_hint = disc_values[0]
            type_hint = pascal(title) if title else pascal(disc_values[0]) if disc_values else pascal(case_hint)
            if kind == "array":
                item_text, _ = self.type_of(variant, decl, "Items", mode)
                if array_variants > 1 and not (isinstance(variant, dict) and "$ref" in variant):
                    inner = self.spec.deref(variant).get("items", {})
                    if isinstance(inner, dict) and "$ref" in inner:
                        case_hint = self.top_names.get(self.spec.ref_name(inner["$ref"]), "array") + "s"
                    elif item_text == "[String]":
                        case_hint = "strings"
                    elif item_text == "[Int]":
                        case_hint = "integers"
                    elif item_text == "[Double]":
                        case_hint = "numbers"
                    elif item_text == "[[Int]]":
                        case_hint = "integerArrays"
                    else:
                        case_hint = f"array{index + 1}"
                elif item_text == "[String]" and array_variants == 1:
                    case_hint = "strings"
                text = item_text
            else:
                text, optional = self.type_of(variant, decl, type_hint, mode)
                if optional and kind != "json":
                    text += "?"
            case = Case(unique(case_hint), text, kind, disc_values, variant.get("description") if isinstance(variant, dict) and "$ref" not in variant else None)
            decl.cases.append(case)
        string_cases = [c for c in decl.cases if c.kind == "string"]
        if len(string_cases) == 1:
            decl.string_literal_case = string_cases[0]

    def ref_case_names(self, refs) -> dict:
        names = {}
        swift_names = [self.top_names.get(self.spec.ref_name(v["$ref"]), self.spec.ref_name(v["$ref"])) for v in refs]
        if len(swift_names) < 2:
            for v, name in zip(refs, swift_names):
                names[v["$ref"]] = name
            return names
        words = [re.findall(r"[A-Z]+(?=[A-Z][a-z0-9]|$|\d)|[A-Z]?[a-z0-9]+|[A-Z]+|\d+", n) for n in swift_names]
        prefix = 0
        while all(len(w) > prefix + 1 for w in words) and len({w[prefix] for w in words}) == 1:
            prefix += 1
        suffix = 0
        while all(len(w) > prefix + suffix + 1 for w in words) and len({w[-1 - suffix] for w in words}) == 1:
            suffix += 1
        for v, w in zip(refs, words):
            core = w[prefix: len(w) - suffix if suffix else None]
            names[v["$ref"]] = "".join(core) if core else "".join(w)
        if len(set(names.values())) != len(names):
            for v, name in zip(refs, swift_names):
                names[v["$ref"]] = name
        return names

    # -- components ---------------------------------------------------------------

    def build_components(self):
        for name, schema in self.spec.schemas.items():
            swift = self.top_names[name]
            stripped, _ = strip_null(schema)
            description = schema.get("description") if isinstance(schema, dict) else None
            if stripped is None:
                self.top[name] = Alias(swift, None, description, "JSONValue")
                continue
            kind = self.component_kind(stripped)
            if kind == "struct":
                decl = Struct(swift, None, description or stripped.get("description"))
                self.top[name] = decl
            elif kind == "enum":
                decl = OpenEnum(swift, None, description or stripped.get("description"))
                self.top[name] = decl
            elif kind == "union":
                decl = Union(swift, None, description or stripped.get("description"))
                self.top[name] = decl
            else:
                self.top[name] = Alias(swift, None, description, None)
        for name, schema in self.spec.schemas.items():
            decl = self.top[name]
            stripped, _ = strip_null(schema)
            if stripped is None:
                continue
            if isinstance(decl, Struct):
                self.fill_struct(decl, stripped, "json")
            elif isinstance(decl, OpenEnum):
                ok, values = self.string_shape(stripped)
                self.fill_open_enum(decl, values or [], stripped)
            elif isinstance(decl, Union):
                variants = stripped.get("oneOf") or stripped.get("anyOf")
                flat = []
                for variant in variants:
                    if isinstance(variant, dict) and ("oneOf" in variant or "anyOf" in variant) and "$ref" not in variant and not variant.get("properties") and "discriminator" not in variant:
                        flat.extend(v for v in (variant.get("oneOf") or variant.get("anyOf")) if not is_null_schema(v))
                    elif not is_null_schema(variant):
                        flat.append(variant)
                resolved = [self.spec.deref(v) for v in flat]
                kinds = [self.variant_kind(v) for v in flat]
                self.fill_union(decl, stripped, flat, resolved, kinds, "json")
            elif isinstance(decl, Alias) and decl.target is None:
                # Inline types an alias needs become top-level types named after it.
                if stripped.get("type") == "array" and isinstance(stripped.get("items"), dict):
                    item_text, item_optional = self.type_of(stripped["items"], None, decl.name + "Element")
                    decl.target = f"[{item_text}{'?' if item_optional else ''}]"
                else:
                    text, _ = self.type_of(stripped, None, decl.name + "Value")
                    decl.target = text

    def component_kind(self, schema) -> str:
        if "$ref" in schema:
            return "alias"
        variants = schema.get("oneOf") or schema.get("anyOf")
        if variants:
            non_null = [v for v in variants if not is_null_schema(v)]
            if len(non_null) == 1:
                inner, _ = strip_null(non_null[0])
                return self.component_kind(inner) if isinstance(inner, dict) else "alias"
            ok, values = self.string_shape(schema)
            if ok:
                refs = [v for v in non_null if isinstance(v, dict) and "$ref" in v and self.string_shape(v)[1]]
                plain = [v for v in non_null if not self.string_shape(v)[1]]
                if len(refs) == 1 and len(refs) + len(plain) == len(non_null):
                    return "alias"
                return "enum" if values else "alias"
            kinds = [self.variant_kind(v) for v in non_null]
            if all(k in ("int", "double") for k in kinds):
                return "alias"
            return "union"
        if "allOf" in schema:
            parts = schema["allOf"]
            if len(parts) == 1 and not schema.get("properties"):
                return "alias"
            if any(not self.is_objectish(p) for p in parts):
                return "alias"
            return "struct"
        if "enum" in schema:
            values = [v for v in schema["enum"] if v is not None]
            if values and all(isinstance(v, str) for v in values) and len(values) > 1:
                return "enum"
            return "alias"
        if schema.get("properties"):
            return "struct"
        return "alias"


