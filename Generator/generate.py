def build_webhook_union(spec: Spec, builder: Builder) -> Decl:
    decl = Union(builder.reserve_top_name("WebhookEvent"), None, "Every event OpenAI can deliver to a webhook endpoint. Use `client.webhooks.unwrap(...)` to verify and decode one.")
    builder.extra_tops.append(decl)
    variants = []
    for name, hook in sorted(spec.doc.get("webhooks", {}).items()):
        post = hook.get("post", {})
        schema = post.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
        if schema and "$ref" in schema:
            variants.append(schema)
    resolved = [spec.deref(v) for v in variants]
    kinds = ["object"] * len(variants)
    builder.fill_union(decl, {"discriminator": {"propertyName": "type"}}, variants, resolved, kinds, "json")
    return decl


